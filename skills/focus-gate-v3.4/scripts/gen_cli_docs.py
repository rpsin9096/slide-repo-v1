#!/usr/bin/env python3
"""Generate references/cli.md from the live argparse registry of focus-gate.py.

Source of truth is build_parser(); the document is derived, never hand-edited.
    python3 scripts/gen_cli_docs.py --write     # regenerate
    python3 scripts/gen_cli_docs.py --check     # exit 1 if the file is stale
"""
import importlib.util
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "references", "cli.md")


def load_parser():
    sys.path.insert(0, ROOT)
    spec = importlib.util.spec_from_file_location("focus_gate_cli", os.path.join(ROOT, "scripts", "focus-gate.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.build_parser()


def render():
    parser = load_parser()
    lines = ["# CLI reference (generated)", "",
             "<!-- GENERATED by scripts/gen_cli_docs.py from the live argparse registry. DO NOT EDIT. -->", "",
             "Run as `python3 scripts/focus-gate.py <flag> [args]`. Most agents need only the commands in SKILL.md.", ""]
    for group in parser._action_groups:
        acts = [a for a in group._group_actions if a.option_strings and a.option_strings[0].startswith("--")]
        if not acts:
            continue
        lines += [f"## {group.title}", ""]
        for a in sorted(acts, key=lambda x: x.option_strings[0]):
            help_ = (a.help or "").replace("|", "\\|")
            lines.append(f"- `{a.option_strings[0]}` — {help_}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def flags():
    return sorted(a.option_strings[0] for a in load_parser()._actions
                  if a.option_strings and a.option_strings[0].startswith("--"))


if __name__ == "__main__":
    text = render()
    if "--write" in sys.argv:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        with open(OUT, "w", encoding="utf-8") as f:
            f.write(text)
        print("wrote", OUT)
    elif "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        sys.exit(0 if cur == text else 1)
    else:
        print(text)
